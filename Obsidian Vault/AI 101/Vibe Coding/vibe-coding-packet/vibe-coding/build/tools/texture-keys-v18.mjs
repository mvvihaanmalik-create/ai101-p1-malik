// Key shared image data by the digest of the embedded bytes, not artist labels.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const assets=new URL('../assets/',import.meta.url),groups=new Map(),keys={};
for(const file of ['guest-v8','butler-v3','child-v5','attendant-v5','porter-v5','porcelain-v15']){
 const b=await readFile(new URL(file+'.glb',assets)),len=b.readUInt32LE(12),j=JSON.parse(b.toString('utf8',20,20+len));
 for(const [i,img] of j.images.entries()){
  const v=j.bufferViews[img.bufferView],start=28+len+(v.byteOffset||0);
  const hash=createHash('sha256').update(b.subarray(start,start+v.byteLength)).digest('hex');
  if(!groups.has(hash))groups.set(hash,[]);groups.get(hash).push([file,i]);
 }
}
for(const [key,g] of groups)if(g.length>1)for(const [file,i] of g)(keys[file]??={})[i]=key;
await writeFile(new URL('../src/texture-identities.js',import.meta.url),'// Generated by tools/texture-keys-v18.mjs.\nexport default '+JSON.stringify(keys,null,2)+';\n');
